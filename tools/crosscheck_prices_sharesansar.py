"""
Independent price check: merolagani (db/prices) vs ShareSansar daily price sheets
================================================================================
Picks a reproducible random sample of trading dates, downloads ShareSansar's full-market
"today share price" sheet for each date, and compares every symbol's RAW open/high/low/close
and volume against db/prices/<SYM>.json.

Why ShareSansar: the official NEPSE API (nepalstock.com.np/api) returns 401 without a token
generated by its client-side protection, and nepsealpha returns 403 to scripts. ShareSansar
serves the same exchange sheet through its normal date-search form (CSRF token + POST).

Usage:
    python tools/crosscheck_prices_sharesansar.py                 # 10 random dates, seed 42
    python tools/crosscheck_prices_sharesansar.py --n 20 --seed 7
    python tools/crosscheck_prices_sharesansar.py --dates 2021-06-10 2024-03-14

Output: .tmp/price_crosscheck_sharesansar.json (per-date and overall agreement)
"""

import argparse
import glob
import html
import json
import os
import random
import re
import statistics
import sys
import time

import httpx

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRICES_DIR = os.path.join(ROOT, "db", "prices")
OUT_PATH = os.path.join(ROOT, ".tmp", "price_crosscheck_sharesansar.json")
PAGE_URL = "https://www.sharesansar.com/today-share-price"
AJAX_URL = "https://www.sharesansar.com/ajaxtodayshareprice"
HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"
    ),
}
# Dates where the merolagani audit found market-wide close-outside-range anomalies.
ANOMALY_DATES = ["2021-06-01", "2021-06-02", "2021-06-10"]
TOL_PCT = 0.5  # a price "matches" if within 0.5%


def load_ours() -> dict:
    """symbol -> {date: [o, h, l, c, v]} from the RAW (as-traded) series."""
    out = {}
    for path in glob.glob(os.path.join(PRICES_DIR, "*.json")):
        if os.path.basename(path).startswith("_"):
            continue
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
        out[doc["symbol"]] = {r[0]: r[1:] for r in doc["raw"]["rows"]}
    return out


def parse_sheet(page: str) -> dict:
    """Parse ShareSansar's price table: symbol -> [open, high, low, close, volume]."""
    m = re.search(r'<table id="headFixed".*?<tbody>(.*?)</tbody>', page, re.S)
    if not m:
        return {}
    rows = {}
    for tr in re.findall(r"<tr>(.*?)</tr>", m.group(1), re.S):
        cells = [re.sub(r"<[^>]+>", "", c).strip() for c in re.findall(r"<td[^>]*>(.*?)</td>", tr, re.S)]
        if len(cells) < 12:
            continue
        sym = html.unescape(cells[1]).strip().upper()
        try:
            # columns: S.No, Symbol, Conf, Open, High, Low, Close, LTP, Close-LTP, %, VWAP, Vol, ...
            o, h, l, c = (float(cells[i].replace(",", "")) for i in (3, 4, 5, 6))
            v = float(cells[11].replace(",", ""))
        except ValueError:
            continue
        rows[sym] = [o, h, l, c, v]
    return rows


def pct(a, b):
    return abs(a - b) / b * 100 if b else (0.0 if a == b else 100.0)


def compare(ours: dict, sheet: dict, date: str) -> dict:
    diffs = {"open": [], "high": [], "low": [], "close": [], "volume": []}
    mismatches = []
    compared = 0
    for sym, theirs in sheet.items():
        mine = ours.get(sym, {}).get(date)
        if not mine:
            continue
        compared += 1
        for k, i in (("open", 0), ("high", 1), ("low", 2), ("close", 3), ("volume", 4)):
            if mine[i] is not None:
                diffs[k].append(pct(mine[i], theirs[i]))
        if mine[3] is not None and pct(mine[3], theirs[3]) > TOL_PCT:
            mismatches.append({"symbol": sym, "ours_close": mine[3], "sharesansar_close": theirs[3],
                               "sharesansar_hl": [theirs[2], theirs[1]]})
    ours_that_day = sum(1 for s in ours.values() if date in s)
    return {
        "date": date,
        "sheet_symbols": len(sheet),
        "our_symbols_that_day": ours_that_day,
        "compared": compared,
        **{f"{k}_match_pct": round(100 * sum(d <= TOL_PCT for d in v) / len(v), 2) if v else None
           for k, v in diffs.items()},
        "close_median_diff_pct": round(statistics.median(diffs["close"]), 4) if diffs["close"] else None,
        "close_mismatches": mismatches[:15],
        "close_mismatch_count": len(mismatches),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, default=10, help="number of random dates")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--dates", nargs="*", help="explicit dates instead of a random sample")
    ap.add_argument("--no-anomaly-dates", action="store_true")
    ap.add_argument("--delay", type=float, default=2.0)
    args = ap.parse_args()

    ours = load_ours()
    all_dates = sorted({d for s in ours.values() for d in s if d >= "2012-01-01"})
    if args.dates:
        dates = args.dates
    else:
        dates = sorted(random.Random(args.seed).sample(all_dates, args.n))
        if not args.no_anomaly_dates:
            dates += ANOMALY_DATES

    client = httpx.Client(headers=HEADERS, timeout=40, follow_redirects=True)
    token = re.search(r'name="_token" value="([^"]+)"', client.get(PAGE_URL).text).group(1)
    results = []
    for d in dates:
        time.sleep(args.delay)
        r = client.post(AJAX_URL, data={"_token": token, "sector": "all_sec", "date": d},
                        headers={"X-Requested-With": "XMLHttpRequest", "Referer": PAGE_URL})
        shown = re.search(r'As of : <span class="text-org">([\d-]+)</span>', r.text)
        sheet = parse_sheet(r.text)
        if r.status_code != 200 or not shown or shown.group(1) != d:
            print(f"{d}: sheet unavailable (HTTP {r.status_code}, shows {shown.group(1) if shown else None})")
            results.append({"date": d, "error": "unavailable"})
            continue
        res = compare(ours, sheet, d)
        results.append(res)
        print(f"{d}: compared {res['compared']}/{res['our_symbols_that_day']}  close match {res['close_match_pct']}%  "
              f"open {res['open_match_pct']}%  high {res['high_match_pct']}%  low {res['low_match_pct']}%  "
              f"vol {res['volume_match_pct']}%  mismatches {res['close_mismatch_count']}")

    random_ok = [r for r in results if "compared" in r and r["date"] not in ANOMALY_DATES]
    total = sum(r["compared"] for r in random_ok)
    matched = sum(r["compared"] * r["close_match_pct"] / 100 for r in random_ok if r["close_match_pct"] is not None)
    summary = {"seed": args.seed, "random_dates": len(random_ok), "symbol_days_compared": total,
               "close_match_pct": round(100 * matched / total, 2) if total else None, "tolerance_pct": TOL_PCT}
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump({"summary": summary, "per_date": results}, f, indent=1)
    print("\nRandom-sample summary:", summary)
    print("Full report:", OUT_PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
